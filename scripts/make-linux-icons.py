#!/usr/bin/env python3
"""Turns Lucide SVG icons (ISC licence, https://lucide.dev) into path strings for linux/SerbiaID.Linux/Icons.cs.

  python3 scripts/make-linux-icons.py <folder with the .svg files> > linux/SerbiaID.Linux/Icons.cs

Every icon is drawn on a 24x24 grid with a 2 px round stroke; circles, rects, lines and polylines become path data."""
import os, re, sys, xml.etree.ElementTree as ET

def f(x): return ("%g" % float(x))

def abs_start(d):
    """Each element starts at the origin, so a leading relative moveto equals an absolute one; coordinate pairs that follow it
    in the same command are relative linetos."""
    m = re.match(r'^\s*m\s*(-?[\d.]+)[\s,]*(-?[\d.]+)(.*)$', d, re.S)
    if not m: return d
    rest = m.group(3)
    return f"M{m.group(1)} {m.group(2)}" + (("l" + rest) if re.match(r'^[\s,]*[-\d.]', rest) else rest)

def conv(el):
    t = el.tag.split('}')[-1]; a = el.attrib
    if t == 'path': return abs_start(a['d'])
    if t == 'circle':
        cx, cy, r = float(a['cx']), float(a['cy']), float(a['r'])
        return f"M{f(cx - r)} {f(cy)}a{f(r)} {f(r)} 0 1 0 {f(2 * r)} 0a{f(r)} {f(r)} 0 1 0 {f(-2 * r)} 0"
    if t == 'ellipse':
        cx, cy, rx, ry = (float(a[k]) for k in ('cx', 'cy', 'rx', 'ry'))
        return f"M{f(cx - rx)} {f(cy)}a{f(rx)} {f(ry)} 0 1 0 {f(2 * rx)} 0a{f(rx)} {f(ry)} 0 1 0 {f(-2 * rx)} 0"
    if t == 'line': return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if t in ('polyline', 'polygon'):
        pts = re.findall(r'-?[\d.]+', a['points']); pairs = list(zip(pts[0::2], pts[1::2]))
        return 'M' + 'L'.join(f"{x} {y}" for x, y in pairs) + ('Z' if t == 'polygon' else '')
    if t == 'rect':
        x, y, w, h = (float(a[k]) for k in ('x', 'y', 'width', 'height'))
        rx = float(a.get('rx', a.get('ry', 0))); ry = float(a.get('ry', rx))
        if rx == 0: return f"M{f(x)} {f(y)}h{f(w)}v{f(h)}h{f(-w)}Z"
        return (f"M{f(x + rx)} {f(y)}H{f(x + w - rx)}a{f(rx)} {f(ry)} 0 0 1 {f(rx)} {f(ry)}V{f(y + h - ry)}a{f(rx)} {f(ry)} 0 0 1 {f(-rx)} {f(ry)}"
                f"H{f(x + rx)}a{f(rx)} {f(ry)} 0 0 1 {f(-rx)} {f(-ry)}V{f(y + ry)}a{f(rx)} {f(ry)} 0 0 1 {f(rx)} {f(-ry)}Z")
    return ''

out = ["// Generated by scripts/make-linux-icons.py from Lucide icons (ISC licence, https://lucide.dev). Do not edit by hand.",
       "namespace SerbiaID;", "", "public static class Icons", "{", "    public static readonly Dictionary<string, string> Paths = new()", "    {"]
for name in sorted(os.listdir(sys.argv[1])):
    if not name.endswith('.svg'): continue
    root = ET.fromstring(re.sub(r'<!--.*?-->', '', open(os.path.join(sys.argv[1], name)).read(), flags=re.S))
    d = ''.join(conv(e) for e in root.iter() if e is not root)
    out.append(f'        ["{name[:-4]}"] = "{d}",')
out += ["    };", "}", ""]
print('\n'.join(out))
